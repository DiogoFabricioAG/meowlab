BEGIN;

CREATE SCHEMA IF NOT EXISTS print_system;
SET LOCAL search_path TO print_system, public;

CREATE TABLE IF NOT EXISTS clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE,
  numero BIGINT UNIQUE,
  descripcion TEXT,
  creado_el TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  estado TEXT
);

CREATE TABLE IF NOT EXISTS ventas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "diseño" TEXT NOT NULL,
  cliente_id BIGINT NOT NULL REFERENCES clientes(id),
  cantidad TEXT,
  metro_total DOUBLE PRECISION,
  maquina TEXT,
  pago DOUBLE PRECISION NOT NULL,
  estado TEXT,
  nota TEXT,
  creado_el TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  fecha TEXT,
  costo_por_metro DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES clientes(id),
  pago DOUBLE PRECISION NOT NULL,
  nota TEXT,
  fecha TEXT DEFAULT TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'America/Lima', 'YYYY-MM-DD')
);

CREATE TABLE IF NOT EXISTS compras (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT NOT NULL,
  categoria TEXT NOT NULL,
  monto DOUBLE PRECISION NOT NULL,
  notas TEXT,
  creado_el TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS activos_fijos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  valor_compra DOUBLE PRECISION NOT NULL,
  fecha_compra TEXT NOT NULL,
  tasa_depreciacion_anual DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  creado_el TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS variables_negocio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave TEXT NOT NULL UNIQUE,
  valor TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ventas_cliente_id ON ventas (cliente_id);
CREATE INDEX IF NOT EXISTS idx_ventas_fecha ON ventas (fecha);
CREATE INDEX IF NOT EXISTS idx_pagos_cliente_id ON pagos (cliente_id);
CREATE INDEX IF NOT EXISTS idx_pagos_fecha ON pagos (fecha);
CREATE INDEX IF NOT EXISTS idx_compras_creado_el ON compras (creado_el);

COMMIT;
