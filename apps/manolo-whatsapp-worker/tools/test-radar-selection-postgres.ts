import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Pool } from "pg";
import { PgRadarSelectionService } from "../src/node/radar/selection-service";
import type { RadarCandidate, RadarSyncRequest } from "../src/radar/sync-contracts";

const connectionString = process.env.RADAR_TEST_DATABASE_URL;
if (!connectionString) throw new Error("RADAR_TEST_DATABASE_URL is required");
const databaseName = decodeURIComponent(new URL(connectionString).pathname.replace(/^\//, ""));
if (databaseName !== "radar_test") {
  throw new Error("Refusing to run: RADAR_TEST_DATABASE_URL must target a database named radar_test");
}

const pool = new Pool({ connectionString, max: 12, connectionTimeoutMillis: 5_000, statement_timeout: 10_000 });
const client = await pool.connect();

const primaryCandidate = (ocid = "ocds-5wno2w-123456789"): RadarCandidate => ({
  alert: {
    ocid,
    code: "AS-10-2026",
    description: "Compra pública de prueba",
    buyer: "Entidad de prueba",
    amount: "S/ 12,000",
    deadline: "2026-11-10",
    sourceUrl: "https://contratacionesabiertas.oece.gob.pe",
  },
});

const richerEvidenceCandidate = (): RadarCandidate => {
  const alert = primaryCandidate("ocds-5wno2w-123456789").alert;
  return {
    alert,
    evidence: {
      sourceUrl: "https://prod4.seace.gob.pe/openegocio/#/ficha/idProceso/tipo/123456789/2",
      observedAt: "2026-10-31T14:00:00.000Z",
      items: [{ description: "Chaleco reflectante", quantity: 24, unit: "unidad" }],
      documents: [],
    },
  };
};

const base = {
  version: 1 as const,
  tenantId: "tenant-a",
  phoneNumberId: "123456789012345",
  whatsappUserId: "51999999999",
  installationId: "install-a",
};
function makeRequest(fields: Partial<RadarSyncRequest> & Pick<RadarSyncRequest, "operation">): RadarSyncRequest {
  return { ...base, requestId: `req-${crypto.randomUUID()}`, ...fields } as RadarSyncRequest;
}
async function execute(request: RadarSyncRequest, stableHash = `hash:${request.requestId}`) {
  return service.execute(request, stableHash);
}
async function count(table: string): Promise<number> {
  const result = await client.query<{ total: string }>(`SELECT COUNT(*)::text AS total FROM ${table}`);
  return Number(result.rows[0].total);
}
function ok(value: unknown, message: string): asserts value {
  assert.ok(value, message);
}

let service: PgRadarSelectionService;
try {
  const nameResult = await client.query<{ current_database: string }>("SELECT current_database()");
  assert.equal(nameResult.rows[0].current_database, "radar_test");
  console.log("[radar-pg] resetting isolated schema");
  // This harness owns only the exact disposable DB name checked above.
  await client.query("DROP SCHEMA IF EXISTS whatsapp CASCADE");
  await client.query("CREATE SCHEMA whatsapp");
  await client.query(`
    CREATE TABLE whatsapp.tenants (
      id TEXT PRIMARY KEY,
      status TEXT NOT NULL CHECK (status IN ('active', 'paused'))
    );
    CREATE TABLE whatsapp.whatsapp_numbers (
      id TEXT PRIMARY KEY,
      tenant_id TEXT NOT NULL REFERENCES whatsapp.tenants(id) ON DELETE CASCADE,
      phone_number_id TEXT NOT NULL UNIQUE,
      active BOOLEAN NOT NULL DEFAULT TRUE,
      UNIQUE (tenant_id, phone_number_id)
    );
    CREATE TABLE whatsapp.contacts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id TEXT NOT NULL REFERENCES whatsapp.tenants(id) ON DELETE CASCADE,
      whatsapp_user_id TEXT NOT NULL,
      active_role_key TEXT,
      UNIQUE (tenant_id, whatsapp_user_id),
      UNIQUE (tenant_id, id)
    );
    CREATE TABLE whatsapp.role_catalog (
      role_key TEXT PRIMARY KEY,
      active BOOLEAN NOT NULL DEFAULT TRUE
    );
    CREATE TABLE whatsapp.bot_configs (
      tenant_id TEXT PRIMARY KEY REFERENCES whatsapp.tenants(id) ON DELETE CASCADE,
      role_key TEXT NOT NULL
    );
    INSERT INTO whatsapp.tenants(id, status) VALUES ('tenant-a', 'active'), ('tenant-b', 'active');
    INSERT INTO whatsapp.whatsapp_numbers(id, tenant_id, phone_number_id) VALUES
      ('number-a', 'tenant-a', '123456789012345'), ('number-b', 'tenant-b', '123456789012346');
    INSERT INTO whatsapp.role_catalog(role_key, active) VALUES ('radar', TRUE), ('cat', TRUE), ('inactive-radar', FALSE);
    INSERT INTO whatsapp.bot_configs(tenant_id, role_key) VALUES ('tenant-a', 'cat'), ('tenant-b', 'cat');
    INSERT INTO whatsapp.contacts(tenant_id, whatsapp_user_id, active_role_key) VALUES
      ('tenant-a', '51999999999', 'radar'),
      ('tenant-a', '51888888888', 'radar'),
      ('tenant-a', '51777777777', 'inactive-radar'),
      ('tenant-b', '51666666666', 'radar');
  `);
  const migration = readFileSync("infra/postgres/migrations/009-radar-selections.sql", "utf8");
  await client.query(migration);
  service = new PgRadarSelectionService(pool);
  console.log("[radar-pg] schema and synthetic authorization fixtures ready");

  const publish = makeRequest({ operation: "publish_candidates", candidates: [primaryCandidate()] });
  const publishHash = "publish-hash-stable";
  assert.equal((await execute(publish, publishHash)).status, "ok");
  assert.deepEqual(await execute(publish, publishHash), await execute(publish, publishHash));

  const evidencePublish = makeRequest({ operation: "publish_candidates", candidates: [richerEvidenceCandidate()] });
  assert.equal((await execute(evidencePublish)).status, "ok");
  const sparseRepublish = makeRequest({ operation: "publish_candidates", candidates: [primaryCandidate()] });
  assert.equal((await execute(sparseRepublish)).status, "ok");
  console.log("[radar-pg] candidate publishing and evidence snapshot checks passed");

  const missing = await execute(makeRequest({
    operation: "select_candidate", ocid: "ocds-5wno2w-999999999", state: "interesting", metaMessageId: "wamid-missing",
  }));
  assert.equal(missing.status, "conflict", "unknown OCIDs cannot be selected");
  assert.equal(await count("whatsapp.radar_selection_changes"), 0, "unknown selection must not leave an event");

  const firstSelect = makeRequest({
    operation: "select_candidate", ocid: "ocds-5wno2w-123456789", state: "interesting", metaMessageId: "wamid-button-1",
  });
  const selected = await execute(firstSelect, "select-hash");
  assert.equal(selected.status, "ok");
  assert.equal(selected.selection?.seq, 1);
  ok(selected.selection?.candidate.evidence, "selection should capture the published evidence snapshot");
  const sameMetaDifferentRequest = makeRequest({
    operation: "select_candidate", ocid: "ocds-5wno2w-123456789", state: "interesting", metaMessageId: "wamid-button-1",
  });
  assert.equal((await execute(sameMetaDifferentRequest, "different-request-hash")).selection?.seq, 1);
  const changedMetaPayload = makeRequest({
    operation: "select_candidate", ocid: "ocds-5wno2w-123456789", state: "dismissed", metaMessageId: "wamid-button-1",
  });
  assert.equal((await execute(changedMetaPayload)).status, "conflict", "same Meta event with changed payload conflicts");
  assert.equal((await execute(makeRequest({ ...firstSelect, requestId: firstSelect.requestId }), "select-hash")).selection?.seq, 1,
    "same request and hash is idempotent");
  assert.equal((await execute(makeRequest({ ...firstSelect, requestId: firstSelect.requestId }), "other-hash")).status, "conflict",
    "same request ID with changed request hash conflicts");
  console.log("[radar-pg] selection and idempotency checks passed");

  const moved = await execute(makeRequest({
    ...firstSelect,
    installationId: "install-a",
    whatsappUserId: "51888888888",
    requestId: "attempt-move-install",
  }));
  assert.equal(moved.status, "forbidden", "installation cannot be rebound to a different authorized contact");

  const foreignCandidate = await execute(makeRequest({
    ...firstSelect,
    tenantId: "tenant-b",
    phoneNumberId: "123456789012346",
    whatsappUserId: "51666666666",
    installationId: "foreign-valid-contact",
  }));
  assert.equal(foreignCandidate.status, "conflict", "valid foreign scope cannot select a candidate published to another scope");
  assert.equal(foreignCandidate.selection, undefined);

  for (const [tenantId, phoneNumberId, whatsappUserId] of [
    ["tenant-a", "123456789012345", "51777777777"],
    ["tenant-a", "123456789012345", "51555555555"],
  ]) {
    const forbidden = await execute(makeRequest({
      ...firstSelect,
      tenantId,
      phoneNumberId,
      whatsappUserId,
      installationId: `forbidden-${tenantId}-${whatsappUserId}`,
    }));
    assert.equal(forbidden.status, "forbidden", `scope/role must be rejected for ${tenantId}/${whatsappUserId}`);
  }
  console.log("[radar-pg] authorization and installation binding checks passed");

  const ackBeforePull = await execute(makeRequest({ operation: "ack_changes", cursor: 1 }));
  assert.equal(ackBeforePull.status, "conflict", "ACK cannot advance beyond a cursor delivered to that installation");

  const firstInstallationPull = await execute(makeRequest({
    operation: "pull_changes", installationId: "install-a", after: 0, limit: 100,
  }));
  assert.equal(firstInstallationPull.changes?.[0].seq, 1);
  assert.equal((await execute(makeRequest({ operation: "ack_changes", installationId: "install-a", cursor: 1 }))).ackedCursor, 1);

  const secondPull = await execute(makeRequest({
    operation: "pull_changes", installationId: "install-b", after: 0, limit: 100,
  }));
  assert.deepEqual(secondPull.changes?.map((item) => item.seq), [1], "another installation receives the account log from its own cursor");
  assert.equal((await execute(makeRequest({ operation: "ack_changes", installationId: "install-b", cursor: 1 }))).ackedCursor, 1);
  console.log("[radar-pg] independent installation cursors and ACK checks passed");

  // Generate enough events to exercise paging and serialized per-account sequence allocation.
  const concurrent = await Promise.all(Array.from({ length: 8 }, (_, index) => execute(makeRequest({
    operation: "select_candidate",
    ocid: "ocds-5wno2w-123456789",
    state: index % 2 ? "dismissed" : "interesting",
    metaMessageId: `wamid-concurrent-${index}`,
  }))));
  assert.ok(concurrent.every((item) => item.status === "ok" && item.selection));
  for (let index = 0; index < 102; index += 1) {
    const response = await execute(makeRequest({
      operation: "select_candidate",
      ocid: "ocds-5wno2w-123456789",
      state: index % 2 ? "dismissed" : "interesting",
      metaMessageId: `wamid-page-${index}`,
    }));
    assert.equal(response.status, "ok");
  }
  const firstPage = await execute(makeRequest({ operation: "pull_changes", after: 0, limit: 100 }));
  assert.equal(firstPage.changes?.length, 100);
  const secondPage = await execute(makeRequest({ operation: "pull_changes", after: firstPage.cursor, limit: 100 }));
  assert.equal(secondPage.changes?.length, 11);
  const ordered = [...(firstPage.changes ?? []), ...(secondPage.changes ?? [])];
  assert.deepEqual(ordered.map((item) => item.seq), Array.from({ length: 111 }, (_, index) => index + 1));
  assert.ok(concurrent.every((item) => item.selection!.seq >= 2 && item.selection!.seq <= 9));
  assert.equal((await client.query<{ state: string }>(
    `SELECT state FROM whatsapp.radar_current_selections WHERE tenant_id='tenant-a' AND ocid='ocds-5wno2w-123456789'`,
  )).rows[0].state, "dismissed", "latest selection state must win");
  assert.equal((await execute(makeRequest({ operation: "pull_changes", installationId: "install-b", after: 0, limit: 10 }))).changes?.[0].seq, 1,
    "one installation's ACK does not consume another installation's feed");
  console.log("[radar-pg] paginated and concurrent account sequence checks passed");

  const emptyPull = await execute(makeRequest({ operation: "pull_changes", after: 111, limit: 10 }));
  assert.equal(emptyPull.cursor, 111, "empty pull retains the caller's after cursor");

  const before = await count("whatsapp.radar_sync_requests");
  const beforeEvents = await count("whatsapp.radar_selection_changes");
  const rollbackRequest = makeRequest({ operation: "publish_candidates", candidates: [null as unknown as RadarCandidate] });
  await assert.rejects(() => execute(rollbackRequest), "invalid service input should fail the transaction");
  assert.equal(await count("whatsapp.radar_sync_requests"), before, "failed transaction must not save idempotency response");
  assert.equal(await count("whatsapp.radar_selection_changes"), beforeEvents, "failed transaction must not leave partial events");
  console.log("[radar-pg] rollback check passed");

  console.log("RADAR PostgreSQL selection integration passed");
} finally {
  client.release();
  await pool.end();
}
